"""تصنيف الخبر من عنوانه وملخصه بقواعد كلمات بسيطة وشفافة (بلا خدمة مدفوعة). الترتيب هو الأولوية:
الوفاة أولاً لأنها الأحوج لسرعة المراجعة، وأي خبر لا يطابق شيئاً يبقى بلا تصنيف (None) بدل تخمين خاطئ."""
from .normalize import find_phrase, tokens

CATEGORY_LABELS = {
    "death": "وفاة", "congrats": "تهنئة", "achievement": "نجاح وتفوق", "services": "خدمات",
    "sports": "رياضة", "weather": "طقس", "incident": "حوادث",
}

RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("death", ("انتقل الى رحمة الله", "ينعى", "تنعى", "نعي", "وفاة", "توفي", "توفيت", "المرحوم", "المرحومة", "تعزية", "عظم الله اجركم", "جنازة", "مشيعين", "رحمه الله")),
    ("incident", ("حادث", "تصادم", "حريق", "جريمة", "انهيار", "غرق", "اصابة", "اصابات", "دهس", "سطو")),
    ("weather", ("ثلوج", "الثلوج", "امطار", "منخفض جوي", "طقس", "عاصفة", "صقيع", "موجة حر", "رياح")),
    ("achievement", ("تفوق", "المتفوقين", "نجاح", "تخرج", "تخريج", "توجيهي", "الاول على", "تكريم", "تكرم", "حصل على", "حصول", "فوز")),
    ("congrats", ("تهنئة", "نهنئ", "نبارك", "مبروك", "الف مبروك", "زفاف", "عرس", "خطوبة", "مولود", "حفل زفاف")),
    ("sports", ("مباراة", "دوري", "بطولة", "نادي", "كرة القدم", "كرة السلة", "لاعب", "فريق")),
    ("services", ("بلدية", "مياه", "كهرباء", "طريق", "الطرق", "شوارع", "نظافة", "مركز صحي", "مدرسة", "مدارس", "اسفلت", "خدمات", "مجلس محلي")),
)


def classify(title: str, summary: str = "") -> str | None:
    """أول فئة (حسب الأولوية) ترد إحدى عباراتها في العنوان؛ إن لم تُوجد فالملخص. None إن لم يطابق شيء."""
    for text in (title, summary):
        tk = tokens(text or "")
        if not tk:
            continue
        for cat, phrases in RULES:
            if any(find_phrase(tk, p) for p in phrases):
                return cat
    return None
